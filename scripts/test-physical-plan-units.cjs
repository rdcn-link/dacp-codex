const fs=require('fs'),vm=require('vm'),assert=require('assert');
const sandbox={window:{}};vm.createContext(sandbox);vm.runInContext(fs.readFileSync('dacp-union-server/src/main/resources/web/dag.js','utf8'),sandbox);
const tasks=['a','b','c'].map(id=>({id,node:'server A',node_identity:'A',operator:'example@1',state:'running',inputs:[]}));
const job={job_id:'test',state:'running',tasks,outputs:{},nodes:{A:{execution_units:[{id:'shared',mode:'shared_process',steps:['a','b'],runtime_image:'sha256:runtime',runtime_name:'python-arrow',runtime_version:'1.0',runtime_dependencies:{python:'3.12'}},{id:'c',mode:'isolated_step',steps:['c'],reason:'boundary'}]}},placement_decisions:[{step:'a',reason:'data_locality'}]};
const fmt={bytes:String,time:String,labels:{},terminal:new Set()};
const model=sandbox.window.DacpDag.buildData(job,new Map(),fmt);
const a=model.data.nodes.find(n=>n.id==='task:a'),b=model.data.nodes.find(n=>n.id==='task:b'),c=model.data.nodes.find(n=>n.id==='task:c');
assert.equal(a.combo,b.combo);assert.notEqual(a.combo,c.combo);
assert.equal(model.data.combos.find(g=>g.id===a.combo).combo,'server:0');
assert(model.details.get('task:a').lines.includes('Placement reason: data_locality'));
assert(model.details.get(a.combo).lines.includes('Runtime: python-arrow@1.0'));
assert(model.details.get(a.combo).lines.includes('Image: sha256:runtime'));
assert(model.data.combos.find(g=>g.id===a.combo).style.labelText.includes('python-arrow@1.0'));
assert(model.details.get(a.combo).lines.includes('python: 3.12'));
const logical=sandbox.window.DacpDag.buildData({...job,logical:true},new Map(),fmt);
assert.equal(logical.data.combos.length,0);assert(!logical.details.get('task:a').lines.some(l=>l.includes('Placement')));
const pending=sandbox.window.DacpDag.buildData({...job,nodes:{}},new Map(),fmt);
assert(!pending.data.combos.some(c=>c.id.startsWith('unit:')));
console.log('Physical execution units, placement inspection, pending and logical plans: passed');
