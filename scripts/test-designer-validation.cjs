const assert=require('node:assert/strict');
require('../xstream-designer/src/main/resources/web/validation.js');
const check=globalThis.WorkflowValidation.check;
const source=id=>({id,operator:'read_item@1.0',inputs:{},params:{uri:'dacp://example/ds/data'}});
const filter={id:'filter',operator:'filter@1',inputs:{source:'read'},params:{}};
const catalog=[{name:'filter',version:'1',inputs:{source:{representations:['records']}}}];
const report={tasks:{read:{outputs:{result:{representations:['records']}},diagnostics:[]},filter:{outputs:{result:{representations:['records']}},diagnostics:[]}}};
const job={tasks:[source('read'),filter],outputs:{result:'filter'}};
assert.deepEqual(check(job,catalog,report),[]);
const codes=j=>check(j,catalog,report).map(x=>x.code);
assert(codes({...job,outputs:{}}).includes('outlet_unconnected'));
assert(codes({...job,tasks:[...job.tasks,source('orphan')]}).includes('disconnected_step'));
assert(codes({...job,tasks:[source('read'),{...filter,inputs:{wrong:'read'}}]}).includes('missing_input'));
assert(codes({...job,tasks:[source('read'),{...filter,inputs:{wrong:'read'}}]}).includes('unexpected_input'));
assert(codes({...job,tasks:[source('read'),{...filter,inputs:{source:'read:absent'}}]}).includes('missing_output'));
assert(codes({...job,tasks:[source('read'),{...filter,inputs:{source:'missing'}}]}).includes('missing_step'));
assert(codes({...job,tasks:[source('read'),{...filter,inputs:{source:'filter'}}]}).includes('cycle'));
assert(codes({...job,outputs:{result:'read'}}).includes('duplicate_consumer'));
const bytes=structuredClone(report);bytes.tasks.read.outputs.result.representations=['bytes'];
assert(check(job,catalog,bytes).some(x=>x.code==='incompatible_input'));
assert(codes({...job,tasks:[{...source('read'),params:{uri:'$URI'}},filter]}).includes('missing_variable'));
console.log('Validation passed: Outlet, reachability, input/output ports, cycles, duplicate consumers, types and variables');
