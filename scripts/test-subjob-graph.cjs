const fs=require('fs'),vm=require('vm'),assert=require('assert');
const src=fs.readFileSync('dacp-union-server/src/main/resources/web/job.js','utf8');
const context={};vm.createContext(context);vm.runInContext(src.slice(src.indexOf('function subjobGraph('),src.indexOf('function renderPlanning(')),context);
const job={job_id:'j',tasks:[{id:'read',node:'A',inputs:[]},{id:'parse',node:'B',inputs:[{task:'read',output_port:'result',port:'input'}]},{id:'filter',node:'B',inputs:[{task:'parse',output_port:'result',port:'input'}]},{id:'save',node:'C',inputs:[{task:'filter',output_port:'result',port:'input'}]}],outputs:{result:{task:'save',port:'result'}}};
const graph=context.subjobGraph(job,{node:'B',steps:['parse','filter']});
assert.deepEqual(graph.tasks.map(t=>t.id),['parse','filter']);
assert.equal(graph.tasks[0].inputs[0].task,undefined);
assert.equal(graph.tasks[0].inputs[0].upstream_origin,'A');
assert.equal(graph.tasks[0].inputs[0].upstream_task,'read');
assert.equal(graph.tasks[1].inputs[0].task,'parse');
assert.deepEqual(graph.outputs,{'filter:result':{task:'filter',port:'result'}});
assert.equal(job.tasks[1].inputs[0].task,'read');
console.log('PASS sub-job graph boundaries and immutable source');
vm.runInContext(src.slice(src.indexOf('function orderSubjobs('),src.indexOf('function renderPlanning(')),context);
const subjobs=[{node:'C',steps:['save']},{node:'B',steps:['parse','filter']},{node:'A',steps:['read']}];
assert.deepEqual(context.orderSubjobs({...job,sub_jobs:subjobs}).map(s=>s.node),['A','B','C']);
const independent={tasks:[{id:'x',inputs:[]},{id:'y',inputs:[]}],sub_jobs:[{node:'Y',steps:['y']},{node:'X',steps:['x']}]};
assert.deepEqual(context.orderSubjobs(independent).map(s=>s.node),['X','Y']);
const cycle={tasks:[{id:'a',inputs:[]},{id:'b',inputs:[{task:'a'}]},{id:'c',inputs:[{task:'b'}]}],sub_jobs:[{node:'B',steps:['b']},{node:'A',steps:['a','c']}]};
assert.deepEqual(context.orderSubjobs(cycle).map(s=>s.node),['A','B']);
console.log('PASS upstream-first sub-job order, independent branches and member-level cycles');
