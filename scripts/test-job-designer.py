        page.locator('[data-output="step_1:result"]').click()
        page.locator('[data-input="step_2:source"]').click()
        expect(page.locator('#notice')).to_contain_text('Connected step_1:result')
        page.locator('#undo').click()
        expect(page.locator('#edges [data-edge]')).to_have_count(0)
        page.locator('#redo').click()
        expect(page.locator('#edges [data-edge]')).to_have_count(1)
        page.locator('#undo').click()
        expect(page.locator('#edges [data-edge]')).to_have_count(0)
        # Port dragging no longer connects; only a completed click starts drawing.
        out = page.locator('[data-output="step_1:result"]').bounding_box()
