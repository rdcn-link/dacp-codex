        page.locator('[data-input="step_2:source"]').hover()
        expect(page.locator('[data-input="step_2:source"]')).to_have_class('connection-target')
        page.locator('[data-input="step_2:source"]').click()
        expect(page.locator('#edges [data-edge]')).to_have_count(1)
        expect(page.locator('#connection-preview')).to_have_count(0)
