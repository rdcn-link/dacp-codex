        page.locator('#edges [data-edge]').click()
        expect(page.locator('#edges path.selected')).to_have_count(1)
        expect(page.locator('#delete-connection')).to_have_count(0)
        assert page.locator('#canvas').evaluate('(e) => getComputedStyle(e).outlineStyle') == 'none'
        page.keyboard.press('Delete')
        expect(page.locator('#edges [data-edge]')).to_have_count(0)
        page.locator('#undo').click()
        expect(page.locator('#edges [data-edge]')).to_have_count(1)
        page.locator('#edges [data-edge]').click()
        page.keyboard.press('Delete')
        expect(page.locator('#edges [data-edge]')).to_have_count(0)
        page.locator('#undo').click()
        page.locator('#edges [data-edge]').click()
        page.keyboard.press('Backspace')
        expect(page.locator('#edges [data-edge]')).to_have_count(0)
        page.locator('#undo').click()
        # The single movable Outlet represents all Job output bindings.
        assert page.locator('[data-job-output]').count() == 0
        expect(page.locator('#outlet')).to_have_attribute('draggable', 'false')
        page.locator('[data-output="step_1:result"]').click()
        page.locator('#outlet-input').click()
        expect(page.locator('#notice')).to_contain_text('consumer')
