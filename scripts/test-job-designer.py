        page.mouse.move(into['x']+into['width']/2, into['y']+into['height']/2, steps=10)
        page.mouse.up()
        expect(page.locator('#edges [data-edge]')).to_have_count(0)
        expect(page.locator('#connection-preview')).to_have_count(0)
        page.locator('[data-output="step_1:result"]').click()
