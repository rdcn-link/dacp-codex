#!/usr/bin/env python3
"""Generate, build, verify and publish 100 thin-JAR Scala document operators."""
import argparse
import base64
import hashlib
import importlib.util
import json
import os
from pathlib import Path
import subprocess
import sys
import zlib
ROOT=Path(__file__).resolve().parents[3];HERE=Path(__file__).resolve().parent
sys.path.insert(0,str(HERE.parent/'common'))
from catalog import CATALOG as PYTHON_CATALOG, parameter_schema
spec=importlib.util.spec_from_file_location('common_builder',HERE.parent/'common/build.py');builder=importlib.util.module_from_spec(spec);spec.loader.exec_module(builder)

def specifications():
    result={k:dict(v) for k,v in PYTHON_CATALOG.items() if not k.startswith('records_')}
    result['text_fold_german']=result.pop('text_casefold');result['text_fold_german']['description']='Lowercase and fold German sharp s / 转小写并展开德语尖音 s'
    result['text_html_unescape_basic']=result.pop('text_html_unescape');result['text_html_unescape_basic']['description']='Decode five basic HTML entities / 解码五种基本 HTML 实体'
    result['bytes_sha384']=result.pop('bytes_blake2b');result['bytes_sha384'].update(description='SHA-384 digest / SHA-384 摘要',expected=hashlib.sha384(b'abc').hexdigest().encode()+b'\n')
    result['bytes_crc32']=result.pop('bytes_gzip_compress');result['bytes_crc32'].update(description='CRC32 decimal checksum / CRC32 十进制校验和',expected=str(zlib.crc32(b'abc')).encode()+b'\n',format='text')
    result['json_pretty']['expected']=b'{\n  "a" : 1\n}'
    extras=[
      ('reverse_characters','Reverse Unicode code points / 反转 Unicode 码点','ab世界','界世ba',{}),
      ('count_characters','Count Unicode code points / 统计 Unicode 码点','ab世界','4\n',{}),
      ('count_lines','Count lines / 统计行数','a\nb\n','2\n',{}),
      ('count_words','Count whitespace-separated words / 按空白统计词数','a b\nc','3\n',{}),
      ('remove_digits','Remove ASCII digits / 删除 ASCII 数字','a1b2','ab',{}),
      ('keep_digits','Keep ASCII digits / 仅保留 ASCII 数字','a1b2','12',{}),
      ('remove_ascii_punctuation','Remove ASCII punctuation / 删除 ASCII 标点','a,b!','ab',{}),
      ('tabs_to_spaces','Expand tabs to four spaces / 制表符转四个空格','a\tb','a    b',{}),
      ('spaces_to_tabs','Four spaces to tab / 四个空格转制表符','a    b','a\tb',{}),
      ('join_lines','Join lines with separator / 用分隔符连接各行','a\nb','a,b',{'separator':','}),
      ('split_words','Split words into lines / 按空白分词并分行','a b\tc','a\nb\nc',{}),
      ('sort_lines_desc','Sort lines descending / 按字典倒序排列各行','a\nb','b\na',{}),
      ('nonempty_count','Count nonblank lines / 统计非空白行','a\n \nb','2\n',{}),
      ('remove_bom','Remove leading Unicode BOM / 去除开头的 Unicode BOM','\ufeffabc','abc',{}),
      ('ensure_newline','Ensure final LF / 确保末尾有 LF','abc','abc\n',{}),
      ('remove_newlines','Remove CR and LF / 删除回车换行','a\r\nb','ab',{}),
      ('ascii_only','Keep ASCII characters / 只保留 ASCII 字符','abc世界','abc',{}),
      ('normalize_nfd','Unicode NFD normalization / Unicode NFD 规范化','é','e\u0301',{}),
      ('normalize_nfkd','Unicode NFKD normalization / Unicode NFKD 规范化','Ａé','Ae\u0301',{}),
      ('strip_accents','Remove Unicode combining marks / 删除 Unicode 组合附加符','café','cafe',{})]
    for n,d,s,e,p in extras:result['text_'+n]=dict(description=d,sample=s.encode(),expected=e.encode(),params=p,format='text',representation='bytes')
    assert len(result)==100
    return result

CATALOG=specifications()
def prepare():
    resource=HERE/'src/main/resources';resource.mkdir(parents=True,exist_ok=True)
    data={k:{'description':s['description'],'sample':base64.b64encode(s['sample']).decode(),'expected':base64.b64encode(s['expected']).decode(),'params':s['params'],'format':s['format']} for k,s in CATALOG.items()}
    (resource/'catalog.json').write_text(json.dumps(data,ensure_ascii=False,indent=2)+'\n')
    entries='package dacp.common\n\n// Generated by build.py; each public entrypoint is independently publishable.\n'+''.join(f'object Op_{k} extends DocumentOperator("{k}")\n' for k in CATALOG)
    (HERE/'src/main/scala/dacp/common/Entrypoints.scala').write_text(entries)

def build(runtime_catalog,destination):
    prepare();subprocess.run(['sbt','package','verifyOperators'],cwd=HERE,check=True)
    jar=HERE/'target/scala-2.13/dacp-common-scala_2.13-1.0.jar';assert jar.exists()
    base=json.loads((runtime_catalog/'identity/1.3/manifest.json').read_text());blobs=destination/'blobs/sha256';blobs.mkdir(parents=True,exist_ok=True)
    def store(data,filename):
        h=hashlib.sha256(data).hexdigest();(blobs/h).write_bytes(data);return dict(sha256=h,size=len(data),filename=filename)
    artifact=store(jar.read_bytes(),jar.name)
    files={str(p.relative_to(HERE)):p.read_bytes() for p in HERE.rglob('*') if p.is_file() and not any(x in ('target','__pycache__') for x in p.relative_to(HERE).parts)}
    source=store(builder.archive(files),'dacp-common-scala-sources.zip')
    runtime=base['runtime'];original=runtime_catalog/'blobs/sha256'/runtime['archive']['sha256'];target=blobs/original.name
    if not target.exists():
        try:os.link(original,target)
        except OSError:__import__('shutil').copyfile(original,target)
    assert hashlib.sha256(target.read_bytes()).hexdigest()==runtime['archive']['sha256']
    for name,s in CATALOG.items():
        m=dict(api_version=2,icon=dict(path='M3 5h18v14H3zM3 10h18M9 5v14',color='#14866b'),name='scala_'+name,version='1.0',parameters=parameter_schema(s['params']),description=s['description']+'; params='+json.dumps(s['params'],ensure_ascii=False,separators=(',',':')),
               inputs={'source':{'representations':['bytes'],'formats':[]}},
               execution={'executor':'jvm','entrypoint':'dacp.common.Op_'+name,'config':{}},runtime=runtime,artifact=artifact,
               provenance={'source_archive':source,'source_repository':'https://github.com/rdcn-link/dacp-codex','build_instructions':'From the project root publish the plugin API and operator SDK locally, then run .venv/bin/python examples/operators/common-scala/build.py. See bundled bilingual instructions. Runtime dependencies are provided by dacp/operator-jvm:1.1.'})
        p=destination/('scala_'+name)/'1.0';p.mkdir(parents=True,exist_ok=True);(p/'manifest.json').write_text(json.dumps(m,ensure_ascii=False))
    print(f'Built {len(CATALOG)} Scala operators; shared JAR {artifact["size"]} bytes; sources {source["size"]} bytes',flush=True)

if __name__=='__main__':
    p=argparse.ArgumentParser(description=__doc__);p.add_argument('--prepare-only',action='store_true');p.add_argument('--runtime-catalog',type=Path,default=ROOT/'.operator-catalog');p.add_argument('--output',type=Path,default=HERE/'target/catalog');a=p.parse_args()
    if a.prepare_only:prepare();sys.exit()
    build(a.runtime_catalog,a.output)
