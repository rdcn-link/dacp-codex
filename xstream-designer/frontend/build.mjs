import {build} from 'esbuild';
import {readFile, writeFile} from 'node:fs/promises';
import {fileURLToPath} from 'node:url';
import path from 'node:path';

const directory = path.dirname(fileURLToPath(import.meta.url));
const web = path.resolve(directory, '../src/main/resources/web');
const lock = JSON.parse(await readFile(path.join(directory, 'package-lock.json'), 'utf8'));
const notices = [];
for (const [location, info] of Object.entries(lock.packages)) {
  if (!location || info.dev) continue;
  const name = location.split('node_modules/').at(-1);
  const license = await readFile(path.join(directory, location, 'LICENSE'), 'utf8');
  notices.push(`${name}@${info.version}\n${license.trim()}`);
}
await build({
  entryPoints: [path.join(directory, 'yaml-editor.js')],
  outfile: path.join(web, 'yaml-editor.js'),
  bundle: true, format: 'iife', minify: true, target: ['es2020'],
  legalComments: 'eof',
  banner: {js: '/* CodeMirror 6 and dependencies: see /editor-licenses.txt. Generated by frontend/build.mjs. */'}
});
await writeFile(path.join(web, 'editor-licenses.txt'), notices.join('\n\n' + '-'.repeat(72) + '\n\n') + '\n');
console.log('Built local YAML editor bundle and dependency license notices.');
